Hash from_hex(std::string_view value){
 Hash out{};if(value.size()!=64)throw std::invalid_argument("Native FMC profile hash");
 auto nibble=[](char c)->unsigned{if(c>='0'&&c<='9')return c-'0';if(c>='A'&&c<='F')return c-'A'+10;throw std::invalid_argument("Native FMC profile hash");};
 for(unsigned i=0;i<32;++i)out[i]=static_cast<std::uint8_t>((nibble(value[i*2])<<4)|nibble(value[i*2+1]));
 return out;
}
