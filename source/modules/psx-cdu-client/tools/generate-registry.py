from pathlib import Path
import json,re,hashlib,struct,argparse
from PIL import Image
root=Path(__file__).resolve().parents[3]/'shared/cdu/shaders'
p=argparse.ArgumentParser();p.add_argument('--output-dir',type=Path);args=p.parse_args()
out=args.output_dir.resolve() if args.output_dir else root/'generated'
r=json.loads((out/'registry.json').read_text(encoding='utf-8'));preset=r['preset'];params=r['parameters']
# Every exposed value must actually occur in the uniform layout.
for p in params:
 p['group']='Geometry' if p['id'].startswith(('geom_','border_')) else 'Mask' if p['id'].startswith('mask_') else 'Gamma / contrast' if p['id'] in ['crt_gamma','lcd_gamma','levels_contrast'] else 'Bloom / light spread' if p['id'].startswith(('bloom','halation','diffusion')) else 'Beam / scanlines'
lookups=preset['textures'].split(';');aliases={p['alias']:p['index'] for p in r['passes'] if p['alias']}
lines=['// Generated by convert.py / generate-registry.py; do not edit.','static const Parameter parameters[]={']
for p in params:lines.append('{"%s",L"%s",L"%s",%sf,%sf,%sf,%sf,%s},'%(p['id'],p['label'],p['group'],repr(float(p['default'])),repr(float(p['minimum'])),repr(float(p['maximum'])),repr(float(p['step'])),str(p.get('fixed',False)).lower()))
lines+=['};'];look=[]
for n,name in enumerate(lookups):
 path=(root/'crt-royale/crt'/preset[name]);im=Image.open(path).convert('RGBA');f=out/f'lookup{n}.rgba';f.write_bytes(im.tobytes());look.append((name,im.width,im.height,preset[name+'_mipmap']=='true',f.name))
lines+=['static const LutDefinition luts[]={']
for name,w,h,mip,f in look:lines.append('{"%s",%d,%d,%s,"%s"},'%(name,w,h,str(mip).lower(),f))
lines+=['};']
for pass_ in r['passes']:
 i=pass_['index'];refs=[s['reflection'] for s in pass_['stages']];tex={t['name']:t for ref in refs for t in ref.get('textures',[])}
